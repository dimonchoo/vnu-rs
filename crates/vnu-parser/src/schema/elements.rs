pub const VOID_ELEMENTS: &[&str] = &[
    "area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param", "source",
    "track", "wbr",
];

#[inline]
pub fn is_standard_html_element(name: &str) -> bool {
    STANDARD_HTML_ELEMENTS
        .binary_search_by(|&probe| {
            let mut p_bytes = probe.bytes();
            let mut n_bytes = name.bytes().map(|b| b.to_ascii_lowercase());
            loop {
                match (p_bytes.next(), n_bytes.next()) {
                    (Some(p), Some(n)) => match p.cmp(&n) {
                        std::cmp::Ordering::Equal => continue,
                        other => return other,
                    },
                    (None, None) => return std::cmp::Ordering::Equal,
                    (None, Some(_)) => return std::cmp::Ordering::Less,
                    (Some(_), None) => return std::cmp::Ordering::Greater,
                }
            }
        })
        .is_ok()
}

#[inline]
pub fn is_void_element(name: &str) -> bool {
    VOID_ELEMENTS.iter().any(|&v| v.eq_ignore_ascii_case(name))
}
